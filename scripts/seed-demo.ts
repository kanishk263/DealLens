/**
 * Populates the LOCAL stack with a synthetic demonstration dataset by driving the real application paths:
 * upload → worker → analysis → (for Meridian) analyst findings, an EBITDA adjustment proposal and a DCF model.
 *
 * - Runs only against a local Supabase URL (same guard as the integration tests).
 * - Uses the three synthetic companies from supabase/seed.sql (run `npm run db:reset` first).
 * - Creates demo data-owner accounts (`*@deallens.test`) with random passwords that are never printed or stored;
 *   they cannot be used to sign in through the UI (Google only). Roles are granted through the normal approval
 *   functions, never by direct table writes.
 * - Northstar and Apex are left "awaiting review" so a real (Google-authenticated, approved) analyst can claim them.
 *
 * Usage: npm run seed:demo   (worker venv required; the worker is run in drain mode by this script)
 */
import "../tests/integration/setup-env";
import { uploadDocument } from "../lib/storage/documents";
import { valueDcf, type DcfInput } from "../lib/valuation/dcf";
import { ENGINE_VERSION } from "../lib/valuation/common";
import { adminClient, analyst, approve, createUser, drainWorker, makeSuperadmin, sampleFile, XLSX, type TestUser } from "../tests/integration/helpers";

const COMPANIES = {
  northstar: { id: "11111111-1111-4111-8111-111111111111", files: [["northstar-financial-statements.xlsx", XLSX, "income_statement"], ["northstar-income-statement.pdf", "application/pdf", "income_statement"]] },
  meridian: { id: "22222222-2222-4222-8222-222222222222", files: [["meridian-financial-statements.xlsx", XLSX, "income_statement"]] },
  apex: { id: "33333333-3333-4333-8333-333333333333", files: [["apex-financial-statements.csv", "text/csv", "income_statement"], ["apex-revenue-by-customer.xlsx", XLSX, "revenue_schedule"]] },
} as const;

async function submit(user: TestUser, company: string, files: readonly (readonly [string, string, string])[]) {
  const { data: sub, error } = await user.client.rpc("create_submission", {
    p_company: company, p_name: "FY2022–FY2024 financial statements (synthetic)", p_deal_type: "financial_due_diligence",
    p_period_start: "2022-01-01", p_period_end: "2024-12-31", p_currency: "USD", p_unit: "thousands",
    p_notes: "Synthetic demonstration submission generated by scripts/seed-demo.ts.",
  });
  if (error) throw error;
  for (const [name, type, category] of files) {
    const up = await uploadDocument(user.client, sub as string, sampleFile(name, type), category as never, 25 * 1024 * 1024, null);
    if (!up.ok) throw new Error(`${name}: ${up.error}`);
  }
  const { error: submitError } = await user.client.rpc("submit_submission", { p_submission: sub });
  if (submitError) throw submitError;
  return sub as string;
}

(async () => {
  const admin = await makeSuperadmin();
  const { data: companies } = await admin.client.from("companies").select("id").eq("is_synthetic", true);
  if ((companies ?? []).length < 3) throw new Error("Synthetic companies missing: run `npm run db:reset` to apply supabase/seed.sql.");
  const subs: Record<string, string> = {};
  for (const [key, c] of Object.entries(COMPANIES)) {
    const owner = await createUser(`demo-${key}`);
    await approve(admin, owner, "company_user", c.id);
    subs[key] = await submit(owner, c.id, c.files);
    console.log(`submitted ${key}`);
  }
  drainWorker();
  console.log("processing complete");

  const demoAnalyst = await analyst(admin, "demo-analyst");
  const sub = subs.meridian;
  await demoAnalyst.client.rpc("claim_submission", { p_submission: sub });
  const finding = (title: string, description: string, visibility: string, severity: string) => demoAnalyst.client.rpc("save_finding", {
    p_id: null, p_submission: sub, p_category: "working_capital", p_title: title, p_description: description, p_severity: severity, p_impact: null,
    p_impact_currency: null, p_source_references: [{ reference: "Balance Sheet!C7:D8" }], p_recommendation: "Agree a normalised working-capital target in the SPA.", p_visibility: visibility,
  });
  await finding("Working capital absorption (synthetic example)", "Trade receivables and inventory grew materially faster than revenue in FY2023 and FY2024, absorbing cash.", "client_visible", "high");
  await finding("Query total assets with management (synthetic example)", "FY2024 total assets exceed the sum of components by 150; requires investigation.", "internal", "medium");
  const { data: fy24 } = await demoAnalyst.client.from("financial_periods").select("id").eq("submission_id", sub).eq("period_label", "FY2024").single();
  await demoAnalyst.client.rpc("propose_ebitda_adjustment", { p_submission: sub, p_period: fy24!.id, p_type: "transaction_costs", p_description: "Advisory fees for aborted sale process (synthetic example)",
    p_amount: 420, p_sign: 1, p_evidence: "Synthetic invoice reference INV-0000", p_rationale: "One-off adviser costs linked to a discontinued transaction (illustrative)." });
  const input: DcfInput = { currency: "USD", baseYearLabel: "FY2024", baseRevenue: 109800, baseNetWorkingCapital: 32976, years: 5,
    revenueGrowth: [0.1, 0.08, 0.06, 0.05, 0.04], ebitdaMargin: [0.11, 0.115, 0.12, 0.12, 0.12], daPctRevenue: [0.03, 0.03, 0.03, 0.03, 0.03],
    capexPctRevenue: [0.035, 0.035, 0.035, 0.035, 0.035], nwcPctRevenue: [0.29, 0.28, 0.27, 0.26, 0.25], taxRate: 0.25, wacc: 0.105, terminalGrowth: 0.02,
    midYear: false, netDebt: null, otherBridgeItems: [] };
  await demoAnalyst.client.rpc("save_valuation_model", { p_submission: sub, p_model_name: "DCF — illustrative base case", p_method: "dcf",
    p_assumptions: { wacc: input.wacc, terminalGrowth: input.terminalGrowth }, p_inputs: input, p_outputs: JSON.parse(JSON.stringify(valueDcf(input))),
    p_currency: "USD", p_engine_version: ENGINE_VERSION, p_comments: "Illustrative assumptions for the synthetic demo." });
  await demoAnalyst.client.rpc("request_reanalysis", { p_submission: sub });
  drainWorker();
  // The bootstrap superadmin was only needed to run approvals through the normal functions; remove it so no
  // privileged demo account remains. (Audit entries keep the actions with the actor set to null.)
  await adminClient().auth.admin.deleteUser(admin.id);
  console.log("Demo data ready: Meridian is in analysis with example findings, an adjustment proposal and a DCF; Northstar and Apex await review.");
})().catch((e) => { console.error(e); process.exit(1); });
